"""
database.py - All communication with Supabase lives here.

The Streamlit interface (app.py) never talks to Supabase directly; it calls
these functions. Every function raises DatabaseError with a friendly message
if the API call fails, so app.py can show a helpful error without exposing
credentials or raw stack traces.

Expected tables (adjust the column names below if yours differ):
  customers: customer_id, plus a name column (customer_name / name /
             full_name, or first_name + last_name)
  products:  product_id, product_name, category, price
  orders:    order_id (generated by the database), customer_id, product_id,
             quantity, unit_price, order_date
"""

from decimal import ROUND_HALF_UP, Decimal

import streamlit as st
from supabase import Client, create_client

from config import get_setting

CUSTOMERS_TABLE = "customers"
PRODUCTS_TABLE = "products"
ORDERS_TABLE = "orders"


class DatabaseError(Exception):
    """A Supabase request failed. The message is safe to show to users."""


# ---------------------------------------------------------------------------
# Connection
# ---------------------------------------------------------------------------
@st.cache_resource(show_spinner=False)
def get_client() -> Client:
    """Create the Supabase client once and reuse it across reruns."""
    url = get_setting("SUPABASE_URL")
    key = get_setting("SUPABASE_KEY")
    if not url or not key:
        raise DatabaseError(
            "Supabase credentials are not configured. Add SUPABASE_URL and "
            "SUPABASE_KEY to Streamlit secrets or your local .env file."
        )
    return create_client(url, key)


def _execute(build_query, action: str):
    """Run a query and convert any failure into a safe DatabaseError.

    build_query is a function that receives the client and returns a query,
    so connection errors and query errors are handled in one place.
    """
    try:
        client = get_client()
        return build_query(client).execute().data
    except DatabaseError:
        raise
    except Exception as exc:
        # Show the error type and Supabase's short explanation (e.g. "Invalid
        # API key"). These messages never include the URL or the key itself.
        detail = getattr(exc, "message", None) or ""
        detail = f" Supabase said: {detail}" if detail else ""
        raise DatabaseError(
            f"Could not {action}. Check your internet connection and Supabase "
            f"settings, then try again. (Error type: {type(exc).__name__}.{detail})"
        ) from exc


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def to_money(value) -> Decimal:
    """Convert a price to a Decimal rounded to cents (avoids float errors)."""
    return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def customer_display_name(row: dict) -> str:
    """Build a readable customer name from whichever name columns exist."""
    for column in ("customer_name", "name", "full_name"):
        if row.get(column):
            return str(row[column])
    full = f"{row.get('first_name') or ''} {row.get('last_name') or ''}".strip()
    return full or f"Customer {row.get('customer_id')}"


def validate_quantity(quantity) -> int:
    """Accept only positive whole numbers. Raises ValueError otherwise."""
    if isinstance(quantity, bool):
        raise ValueError("Quantity must be a whole number.")
    if isinstance(quantity, float):
        if not quantity.is_integer():
            raise ValueError("Quantity must be a whole number.")
        quantity = int(quantity)
    if not isinstance(quantity, int):
        try:
            quantity = int(str(quantity).strip())
        except ValueError:
            raise ValueError("Quantity must be a whole number.") from None
    if quantity < 1:
        raise ValueError("Quantity must be at least 1.")
    return quantity


# ---------------------------------------------------------------------------
# Read functions
# ---------------------------------------------------------------------------
def fetch_customers() -> list[dict]:
    rows = _execute(
        lambda c: c.table(CUSTOMERS_TABLE).select("*").order("customer_id"),
        "load customers",
    )
    return [
        {"customer_id": r["customer_id"], "customer_name": customer_display_name(r)}
        for r in rows
    ]


def fetch_products() -> list[dict]:
    rows = _execute(
        lambda c: c.table(PRODUCTS_TABLE)
        .select("product_id, product_name, category, price")
        .order("product_id"),
        "load products",
    )
    return [{**r, "price": to_money(r["price"])} for r in rows]


def get_customer(customer_id) -> dict | None:
    rows = _execute(
        lambda c: c.table(CUSTOMERS_TABLE).select("*").eq("customer_id", customer_id).limit(1),
        "look up the customer",
    )
    if not rows:
        return None
    return {"customer_id": rows[0]["customer_id"], "customer_name": customer_display_name(rows[0])}


def get_product(product_id) -> dict | None:
    """Fetch one product, including its *current* price, straight from Supabase."""
    rows = _execute(
        lambda c: c.table(PRODUCTS_TABLE)
        .select("product_id, product_name, category, price")
        .eq("product_id", product_id)
        .limit(1),
        "look up the product",
    )
    if not rows:
        return None
    return {**rows[0], "price": to_money(rows[0]["price"])}


def fetch_order(order_id) -> dict | None:
    """Retrieve a single saved order by its database-generated ID."""
    rows = _execute(
        lambda c: c.table(ORDERS_TABLE).select("*").eq("order_id", order_id).limit(1),
        "retrieve the saved order",
    )
    return rows[0] if rows else None


def fetch_orders() -> list[dict]:
    """Retrieve all orders, newest first."""
    return _execute(
        lambda c: c.table(ORDERS_TABLE).select("*").order("order_id", desc=True),
        "load order history",
    )


# ---------------------------------------------------------------------------
# Write function
# ---------------------------------------------------------------------------
def insert_order(customer_id, product_id, quantity: int, unit_price: Decimal, order_date: str):
    """Insert one order and return the order_id generated by the database.

    order_id is intentionally NOT sent - the database generates it.
    Returns None if the insert succeeded but no row came back.
    """
    payload = {
        "customer_id": customer_id,
        "product_id": product_id,
        "quantity": validate_quantity(quantity),
        "unit_price": float(to_money(unit_price)),
        "order_date": order_date,
    }
    rows = _execute(lambda c: c.table(ORDERS_TABLE).insert(payload), "save the order")
    if rows and rows[0].get("order_id") is not None:
        return rows[0]["order_id"]
    return None
